/** Short Egyptian Arabic replies with light variation (WhatsApp-friendly). */

function pick<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)]!;
}

export function replyGreeting(userText: string): string {
  const t = userText.trim();
  if (/صباح/.test(t)) {
    return pick([
      'صباح الخير يا باشا 🌟\nلو تحب نجهّز امتحان قولّي على الدرس أو ابعت ملف الأسئلة.',
      'صباح النور!\nجاهز لما تحب: امتحان من البنك أو من ملف/صور.',
    ]);
  }
  if (/مساء/.test(t)) {
    return pick([
      'مساء الخير!\nتحب نبدأ في امتحان، ولا عندك سؤال؟',
      'مساء النور يا فندم.\nقولّي عايز تعمل إيه في الامتحانات.',
    ]);
  }
  if (/إزيك|ازيك|عامل إيه|اخبارك/.test(t)) {
    return pick([
      'الحمد لله تمام، أنت كمان؟\nلو محتاج امتحان أو تعديل قولّي.',
      'بخير والله، تحت أمرك.\nعايز نعمل امتحان ولا نعدّل واحد موجود؟',
    ]);
  }
  return pick([
    'وعليكم السلام ورحمة الله!\nإزاي أقدر أساعدك في الامتحانات؟',
    'أهلاً بيك!\nتقدر تبعت طلب امتحان، ملف أسئلة، أو تسألني عن اللي أقدر أعمله.',
    'مرحبا!\nجاهز أساعدك في إنشاء أو تعديل الامتحانات.',
  ]);
}

export function replyThanks(): string {
  return pick([
    'العفو، أي خدمة 🙏',
    'تحت أمرك في أي وقت.',
    'الله يخليك، لو احتجت حاجة تانية أنا هنا.',
  ]);
}

export function replyHelp(): string {
  return [
    'أقدر أساعدك في:',
    '• إنشاء امتحان من بنك الأسئلة أو من ملف/صور',
    '• مراجعة الأسئلة المستخرجة قبل النشر',
    '• تعديل امتحان اتعمل في المحادثة (حذف/إضافة/تغيير سؤال…)',
    '• نشر المسودة لما توافق',
    '',
    'مثال: «اعمل امتحان 15 سؤال على درس الهرمونات» أو ابعت صورة الأسئلة.',
  ].join('\n');
}

export function replyUnclear(): string {
  return pick([
    'مش واضح قصدي بالظبط.\nتحب نعمل امتحان جديد، نعدّل امتحان موجود، ولا تراجع ملف أسئلة؟',
    'وضّحلي المطلوب لو سمحت: إنشاء امتحان، تعديل، ولا استقبال ملف؟',
  ]);
}

export function replyChitchat(fallback?: string | null): string {
  if (fallback?.trim()) return fallback.trim().slice(0, 400);
  return pick([
    'تمام، أنا هنا لو حابب نشتغل على امتحان.',
    'ماشي. لما تكون جاهز قولّي عايز امتحان من البنك ولا من ملف.',
  ]);
}

export function replyMediaAskIntent(hasDraft: boolean): string {
  const addLine = hasDraft
    ? '• أو «ضيفهم على الامتحان الحالي»'
    : '• أو حدّد امتحان عشان أضيف الأسئلة عليه';
  return [
    'استلمت الملف ✅',
    'تحب أعمل إيه؟',
    '• اعمل امتحان من الأسئلة دي',
    '• راجع الأسئلة بس من غير إنشاء',
    addLine,
    '',
    'ولو هتبعت ملفات تانية ابعتها، وبعدين «خلصت».',
  ].join('\n');
}
