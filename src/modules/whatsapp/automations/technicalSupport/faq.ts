import { HUMAN_SUPPORT_WHATSAPP } from './prompts';

export type HelpTopic =
  | 'login'
  | 'signup'
  | 'forgot_password'
  | 'wrong_url'
  | 'account_locked'
  | 'general';

export { HUMAN_SUPPORT_WHATSAPP };

